-- Postgres schema for vonta_genta_db
-- Create the database first, then run this script against it:
--   CREATE DATABASE vonta_genta_db WITH ENCODING 'UTF8';

BEGIN;

DROP TABLE IF EXISTS userorgs CASCADE;
DROP TABLE IF EXISTS timesheets CASCADE;
DROP TABLE IF EXISTS revenues CASCADE;
DROP TABLE IF EXISTS orginvites CASCADE;
DROP TABLE IF EXISTS datalogs CASCADE;
DROP TABLE IF EXISTS costentries CASCADE;
DROP TABLE IF EXISTS projects CASCADE;
DROP TABLE IF EXISTS costcategories CASCADE;
DROP TABLE IF EXISTS clients CASCADE;
DROP TABLE IF EXISTS orgs CASCADE;
DROP TABLE IF EXISTS countries CASCADE;
DROP TABLE IF EXISTS currencies CASCADE;
DROP TABLE IF EXISTS aspnetusertokens CASCADE;
DROP TABLE IF EXISTS aspnetuserroles CASCADE;
DROP TABLE IF EXISTS aspnetuserlogins CASCADE;
DROP TABLE IF EXISTS aspnetuserclaims CASCADE;
DROP TABLE IF EXISTS aspnetroleclaims CASCADE;
DROP TABLE IF EXISTS aspnetusers CASCADE;
DROP TABLE IF EXISTS aspnetroles CASCADE;
DROP TABLE IF EXISTS apptimezones CASCADE;
DROP TABLE IF EXISTS appactions CASCADE;

CREATE TABLE appactions (
  id int NOT NULL,
  name varchar(255) NOT NULL,
  PRIMARY KEY (id)
);

CREATE TABLE apptimezones (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  zoneid varchar(255) NOT NULL,
  friendlyname varchar(1000) NOT NULL
);

CREATE TABLE aspnetroles (
  id varchar(255) NOT NULL,
  name varchar(256),
  normalizedname varchar(256),
  concurrencystamp text,
  PRIMARY KEY (id),
  CONSTRAINT rolenameindex UNIQUE (normalizedname)
);

CREATE TABLE aspnetusers (
  id varchar(255) NOT NULL,
  username varchar(256),
  normalizedusername varchar(256),
  email varchar(256),
  normalizedemail varchar(256),
  emailconfirmed boolean NOT NULL,
  passwordhash text,
  securitystamp text,
  concurrencystamp text,
  phonenumber text,
  phonenumberconfirmed boolean NOT NULL,
  twofactorenabled boolean NOT NULL,
  lockoutend timestamptz,
  lockoutenabled boolean NOT NULL,
  accessfailedcount int NOT NULL,
  firstnames text,
  lastname text,
  timezoneid int NOT NULL DEFAULT 1,
  PRIMARY KEY (id),
  CONSTRAINT usernameindex UNIQUE (normalizedusername)
);

CREATE INDEX emailindex ON aspnetusers (normalizedemail);
CREATE INDEX fk_aspnetusers_apptimezones_timezoneid ON aspnetusers (timezoneid);

ALTER TABLE aspnetusers
  ADD CONSTRAINT fk_aspnetusers_apptimezones_timezoneid
    FOREIGN KEY (timezoneid) REFERENCES apptimezones (id) ON DELETE RESTRICT;

CREATE TABLE aspnetroleclaims (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  roleid varchar(255) NOT NULL,
  claimtype text,
  claimvalue text
);

CREATE INDEX ix_aspnetroleclaims_roleid ON aspnetroleclaims (roleid);

ALTER TABLE aspnetroleclaims
  ADD CONSTRAINT fk_aspnetroleclaims_aspnetroles_roleid
    FOREIGN KEY (roleid) REFERENCES aspnetroles (id) ON DELETE RESTRICT;

CREATE TABLE aspnetuserclaims (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  userid varchar(255) NOT NULL,
  claimtype text,
  claimvalue text
);

CREATE INDEX ix_aspnetuserclaims_userid ON aspnetuserclaims (userid);

ALTER TABLE aspnetuserclaims
  ADD CONSTRAINT fk_aspnetuserclaims_aspnetusers_userid
    FOREIGN KEY (userid) REFERENCES aspnetusers (id) ON DELETE RESTRICT;

CREATE TABLE aspnetuserlogins (
  loginprovider varchar(128) NOT NULL,
  providerkey varchar(128) NOT NULL,
  providerdisplayname text,
  userid varchar(255) NOT NULL,
  PRIMARY KEY (loginprovider, providerkey)
);

CREATE INDEX ix_aspnetuserlogins_userid ON aspnetuserlogins (userid);

ALTER TABLE aspnetuserlogins
  ADD CONSTRAINT fk_aspnetuserlogins_aspnetusers_userid
    FOREIGN KEY (userid) REFERENCES aspnetusers (id) ON DELETE RESTRICT;

CREATE TABLE aspnetuserroles (
  userid varchar(255) NOT NULL,
  roleid varchar(255) NOT NULL,
  PRIMARY KEY (userid, roleid)
);

CREATE INDEX ix_aspnetuserroles_roleid ON aspnetuserroles (roleid);

ALTER TABLE aspnetuserroles
  ADD CONSTRAINT fk_aspnetuserroles_aspnetroles_roleid
    FOREIGN KEY (roleid) REFERENCES aspnetroles (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_aspnetuserroles_aspnetusers_userid
    FOREIGN KEY (userid) REFERENCES aspnetusers (id) ON DELETE RESTRICT;

CREATE TABLE aspnetusertokens (
  userid varchar(255) NOT NULL,
  loginprovider varchar(128) NOT NULL,
  name varchar(128) NOT NULL,
  value text,
  PRIMARY KEY (userid, loginprovider, name)
);

ALTER TABLE aspnetusertokens
  ADD CONSTRAINT fk_aspnetusertokens_aspnetusers_userid
    FOREIGN KEY (userid) REFERENCES aspnetusers (id) ON DELETE RESTRICT;

CREATE TABLE currencies (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  code varchar(5) NOT NULL,
  symbol varchar(5)
);

CREATE TABLE countries (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  defaultcurrencyid int NOT NULL
);

CREATE INDEX fk_countries_currencies_defaultcurrencyid ON countries (defaultcurrencyid);

ALTER TABLE countries
  ADD CONSTRAINT fk_countries_currencies_defaultcurrencyid
    FOREIGN KEY (defaultcurrencyid) REFERENCES currencies (id) ON DELETE RESTRICT;

CREATE TABLE orgs (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  description varchar(1000),
  appuserid varchar(255) NOT NULL,
  countryid int NOT NULL DEFAULT 0
);

CREATE INDEX ix_org_appuserid ON orgs (appuserid);
CREATE INDEX fk_orgs_countries_countryid ON orgs (countryid);

ALTER TABLE orgs
  ADD CONSTRAINT fk_orgs_aspnetusers_appuserid
    FOREIGN KEY (appuserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT;

CREATE TABLE clients (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  description varchar(1000),
  appuserid varchar(255) NOT NULL,
  orgid int NOT NULL DEFAULT 0
);

CREATE INDEX ix_clients_appuserid ON clients (appuserid);
CREATE INDEX ix_clients_orgid ON clients (orgid);

ALTER TABLE clients
  ADD CONSTRAINT fk_clients_aspnetusers_appuserid
    FOREIGN KEY (appuserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_clients_orgs_orgid
    FOREIGN KEY (orgid) REFERENCES orgs (id) ON DELETE RESTRICT;

CREATE TABLE costcategories (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  description varchar(1000),
  appuserid varchar(255) NOT NULL,
  orgid int NOT NULL DEFAULT 0
);

CREATE INDEX ix_costcategories_appuserid ON costcategories (appuserid);
CREATE INDEX ix_costcategories_orgid ON costcategories (orgid);

ALTER TABLE costcategories
  ADD CONSTRAINT fk_costcategories_aspnetusers_appuserid
    FOREIGN KEY (appuserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_costcategories_orgs_orgid
    FOREIGN KEY (orgid) REFERENCES orgs (id) ON DELETE RESTRICT;

CREATE TABLE projects (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  description varchar(1000),
  startdate timestamp NOT NULL,
  enddate timestamp NOT NULL,
  appuserid varchar(255) NOT NULL,
  clientid int NOT NULL
);

CREATE INDEX ix_projects_appuserid ON projects (appuserid);
CREATE INDEX fk_projects_clients_clientid ON projects (clientid);

ALTER TABLE projects
  ADD CONSTRAINT fk_projects_aspnetusers_appuserid
    FOREIGN KEY (appuserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_projects_clients_clientid
    FOREIGN KEY (clientid) REFERENCES clients (id) ON DELETE RESTRICT;

CREATE TABLE costentries (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entrydate timestamp NOT NULL,
  name varchar(255) NOT NULL,
  description varchar(1000),
  categoryid int NOT NULL DEFAULT 0,
  amount decimal(9,2) NOT NULL DEFAULT 0.00,
  appuserid varchar(255) NOT NULL,
  projectid int NOT NULL DEFAULT 0,
  currencyid int NOT NULL
);

CREATE INDEX ix_costentries_appuserid ON costentries (appuserid);
CREATE INDEX ix_costentries_projectid ON costentries (projectid);
CREATE INDEX fk_costentries_costcategories_categoryid ON costentries (categoryid);
CREATE INDEX fk_costentries_currencies_currencyid ON costentries (currencyid);

ALTER TABLE costentries
  ADD CONSTRAINT fk_costentries_aspnetusers_appuserid
    FOREIGN KEY (appuserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_costentries_costcategories_categoryid
    FOREIGN KEY (categoryid) REFERENCES costcategories (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_costentries_currencies_currencyid
    FOREIGN KEY (currencyid) REFERENCES currencies (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_costentries_projects_projectid
    FOREIGN KEY (projectid) REFERENCES projects (id) ON DELETE RESTRICT;

CREATE TABLE datalogs (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entityname varchar(150) NOT NULL,
  entityid int NOT NULL,
  action int NOT NULL,
  entrytimestamp timestamp NOT NULL,
  appuserid varchar(255) NOT NULL,
  json text NOT NULL
);

CREATE TABLE orginvites (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  touserid varchar(255) NOT NULL,
  orgid int NOT NULL,
  CONSTRAINT ix_orginvites_touserid_orgid UNIQUE (touserid, orgid)
);

CREATE INDEX ix_orginvites_orgid ON orginvites (orgid);

ALTER TABLE orginvites
  ADD CONSTRAINT fk_orginvites_aspnetusers_touserid
    FOREIGN KEY (touserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_orginvites_orgs_orgid
    FOREIGN KEY (orgid) REFERENCES orgs (id) ON DELETE RESTRICT;

CREATE TABLE revenues (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  description varchar(1000),
  entrydate timestamp NOT NULL,
  amount decimal(9,2) NOT NULL DEFAULT 0.00,
  appuserid varchar(255) NOT NULL,
  projectid int NOT NULL DEFAULT 0,
  currencyid int NOT NULL
);

CREATE INDEX ix_revenues_appuserid ON revenues (appuserid);
CREATE INDEX ix_revenues_projectid ON revenues (projectid);
CREATE INDEX fk_revenues_currencies_currencyid ON revenues (currencyid);

ALTER TABLE revenues
  ADD CONSTRAINT fk_revenues_aspnetusers_appuserid
    FOREIGN KEY (appuserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_revenues_currencies_currencyid
    FOREIGN KEY (currencyid) REFERENCES currencies (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_revenues_projects_projectid
    FOREIGN KEY (projectid) REFERENCES projects (id) ON DELETE RESTRICT;

CREATE TABLE timesheets (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(255) NOT NULL,
  description varchar(1000),
  datetimestart timestamp NOT NULL,
  datetimeend timestamp,
  appuserid varchar(255) NOT NULL,
  projectid int NOT NULL DEFAULT 0
);

CREATE INDEX ix_timesheets_appuserid ON timesheets (appuserid);
CREATE INDEX ix_timesheets_projectid ON timesheets (projectid);

ALTER TABLE timesheets
  ADD CONSTRAINT fk_timesheets_aspnetusers_appuserid
    FOREIGN KEY (appuserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_timesheets_projects_projectid
    FOREIGN KEY (projectid) REFERENCES projects (id) ON DELETE RESTRICT;

CREATE TABLE userorgs (
  id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  appuserid varchar(255) NOT NULL,
  orgid int NOT NULL,
  isactive boolean NOT NULL DEFAULT false,
  CONSTRAINT ix_userorgs_appuserid_orgid UNIQUE (appuserid, orgid)
);

CREATE INDEX ix_userorgs_orgid ON userorgs (orgid);

ALTER TABLE userorgs
  ADD CONSTRAINT fk_userorgs_aspnetusers_appuserid
    FOREIGN KEY (appuserid) REFERENCES aspnetusers (id) ON DELETE RESTRICT,
  ADD CONSTRAINT fk_userorgs_orgs_orgid
    FOREIGN KEY (orgid) REFERENCES orgs (id) ON DELETE RESTRICT;

COMMIT;
